import { test, expect } from '@playwright/test';
test('source Ethiopia, review evidence, approve edited mock outreach, classify reply and hand off', async ({page}) => {
  await page.goto('/login');
  await page.getByRole('button',{name:'Enter local workspace'}).click();
  await page.getByRole('link',{name:/Find Suppliers/}).click();
  await expect(page.getByLabel('Country or target market')).toHaveValue('Ethiopia');
  await page.getByRole('button',{name:'Start discovery'}).click();
  await expect(page.getByRole('link',{name:/Dawn Ridge Producer Collective/}).first()).toBeVisible({timeout:45000});
  await page.getByRole('link',{name:/Dawn Ridge Producer Collective/}).first().click();
  await page.getByRole('tab',{name:'Evidence',exact:true}).click();
  await expect(page.getByText('FICTIONAL', {exact:false}).first()).toBeVisible();
  await expect(page.getByRole('heading',{name:'Evidence profile'})).toBeVisible();
  await page.getByRole('tab',{name:'Score breakdown'}).click();
  await expect(page.getByRole('heading',{name:'Supplier / Producer Relevance'})).toBeVisible();
  await page.getByRole('tab',{name:'Human review'}).click();
  await page.getByRole('button',{name:'Approve candidate',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Saved');
  await page.getByRole('tab',{name:'Outreach',exact:true}).click();
  const emailEditors = page.locator('.form-panel').filter({has:page.getByRole('heading',{name:'Email draft',exact:true})});
  const previousDrafts = await emailEditors.count();
  await page.getByRole('button',{name:'Generate email draft'}).click();
  await expect(emailEditors).toHaveCount(previousDrafts + 1);
  const editor = emailEditors.first();
  await expect(editor.getByLabel('Message')).toBeVisible();
  await editor.getByLabel('Message').fill('Hello Dawn Ridge team, we would like to explore sourcing coffee. Could you share your current offer list and sample availability? Thank you, Qima Coffee');
  await editor.getByRole('button',{name:'Save draft changes'}).click();
  await expect(editor.getByText(/Version 2/)).toBeVisible();
  await editor.getByRole('button',{name:'Approve this version'}).click();
  await editor.getByRole('button',{name:'Send simulated email'}).click();
  await expect(editor.getByText(/SENT/).first()).toBeVisible();
  await page.getByRole('tab',{name:'Conversation',exact:true}).click();
  const classifications = page.getByLabel('Human classification correction');
  const previousReplies = await classifications.count();
  await page.getByRole('button',{name:'Simulate & classify reply'}).click();
  await expect(classifications).toHaveCount(previousReplies + 1);
  await expect(classifications.first()).toHaveValue('OFFER_RECEIVED');
  await page.getByRole('tab',{name:'Handoff',exact:true}).click();
  await page.getByRole('button',{name:'Create handoff summary'}).click();
  await expect(page.getByRole('heading',{name:'Handoff ready'}).first()).toBeVisible();
});
